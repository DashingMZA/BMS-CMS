// The theme's chrome, in the site's language.
//
// `archiveText` covers the words around a post and a listing. This covers the
// rest of what the theme itself says: the search box, the menus, the slider
// and modal controls, the comment form. All of it was written in English on
// every site — an Arabic blog asked for "Your comment" under an Arabic heading
// and told a screen reader "Open menu", "Back to top", "Next slide".
//
// Two tables rather than one because they are two vocabularies, and because
// `archiveText` is built from a positional constructor that is already at 21
// arguments; adding twenty more would make a silent off-by-one inevitable.
// This one is keyed, so a missing or misplaced string is a type error.
//
// Same rule as the other tables: the languages the picker offers most often,
// English for everything else.

import { counted, type PluralForms } from "./plural";

export interface UiText {
  /* Search — the header box, the sidebar widget and the results page. */
  search: string;
  searchPlaceholder: string;
  openSearch: string;
  closeSearch: string;
  /** The results heading. The quotes are part of the wording, so each
   *  language brings the pair it actually uses. */
  searchResultsFor: (query: string) => string;
  noResults: string;

  /* Header and page chrome. */
  openMenu: string;
  menu: string;
  closeMenu: string;
  language: string;
  backToTop: string;
  toggleDarkMode: string;
  toggleToc: string;
  close: string;
  map: string;

  /* Slider. `carousel` and `slide` are aria-roledescription, which the spec
     says must be in the language of the page, not in English. */
  carousel: string;
  slide: string;
  prevSlide: string;
  nextSlide: string;
  /** Each slide's accessible name: "3 of 8". */
  slideOf: (i: number, total: number) => string;
  /** The play button on a lazy-loaded video placeholder. */
  playVideo: string;
  playVideoTitled: (title: string) => string;

  /** A countdown whose author never set an end date, and one that has passed. */
  offerEnded: string;

  /* Comments — the section heading, then the form. */
  leaveAComment: string;
  comments: (n: number) => string;
  yourName: string;
  yourEmail: string;
  yourWebsite: string;
  yourComment: string;
  postComment: string;
  posting: string;
  commentPending: string;
  commentPosted: string;

  /* An author line with nothing to show. */
  postsBy: (name: string) => string;
  siteTeam: string;

  /* A countdown block whose date was never set. */
  noDateSet: string;
  /** The language key that matched — for `Intl` formatting in the same language. */
  lang: string;
  /** Business Info: a day with no opening hours. */
  closedLabel: string;
  /** Form validation. `{field}` is replaced with the field's label. */
  fieldRequired: string;
  invalidEmail: string;
  /** Default label on the contact form's submit button. */
  sendMessage: string;
  /** Comment reply controls. */
  reply: string;
  cancelReply: string;
  /** The first focusable thing on every page: jumps past the header. */
  skipToContent: string;
  /** The before/after slider's accessible name when the author set no labels. */
  compareImages: string;
  /** The slider's autoplay button (WCAG 2.2.2: moving content can be paused). */
  pauseSlides: string;
  playSlides: string;
}

/** A table row: the forms of "comment", not yet a function of `n`. */
type UiEntry = Omit<UiText, "comments" | "lang" | "skipToContent" | keyof MediaControls> & { commentForms: PluralForms };

