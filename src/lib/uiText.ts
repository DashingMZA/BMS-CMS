/** The chrome wording for a language tag (`ar`, `ar-EG`), English when there is none. */
export function uiText(language: string): UiText {
  const base = (language || "").split("-")[0].toLowerCase();
  // Matched key, not the requested one — see archiveText for why.
  const key = TEXT[language] ? language : TEXT[base] ? base : "en";
  const { commentForms, ...rest } = TEXT[key];
  // `lang` is the key that MATCHED, not the one asked for. Anything that
  // formats with `Intl` (weekday names, numbers) must use the same language
  // the surrounding text came from, or an Urdu page falls back to English
  // wording next to Urdu day names.
  return {
    ...rest,
    lang: key,
    comments: (n) => counted(key, n, commentForms),
    skipToContent: SKIP_TO_CONTENT[key] ?? SKIP_TO_CONTENT.en,
    ...(MEDIA_CONTROLS[key] ?? MEDIA_CONTROLS.en),
  };
}
